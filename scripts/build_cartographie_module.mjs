import {readFileSync, writeFileSync} from 'node:fs';
// Compact copy of data/cartographie.json for the private Worker (Ambre).
// Sources and long descriptions stay on the public page; the Worker needs only
// identifiers, labels and the ranking inputs used by static/js/cartographie.js.
const data=JSON.parse(readFileSync(new URL('../data/cartographie.json',import.meta.url),'utf8'));
const STRENGTHS=['forte','critere','moderee','limitee','theorique'];
const fail=message=>{throw new Error('Invalid cartographie: '+message);};
const unique=(items,name)=>{const ids=new Set();for(const item of items){if(typeof item.id!=='string'||!/^[a-z0-9_]{1,80}$/.test(item.id)||ids.has(item.id))fail(name+' id '+item.id);if(typeof item.label!=='string'||!item.label.trim())fail(name+' label '+item.id);ids.add(item.id);}return ids;};
if(!Array.isArray(data.factors)||!Array.isArray(data.outcomes)||!Array.isArray(data.links))fail('missing lists');
const factorIds=unique(data.factors,'factor'),outcomeIds=unique(data.outcomes,'outcome');
const weights={};for(const strength of STRENGTHS){const value=(data.weights||{})[strength];if(!Number.isFinite(value)||value<=0)fail('weight '+strength);weights[strength]=value;}
const pairs=new Set();
const links=data.links.map(link=>{
  if(!factorIds.has(link.factor)||!outcomeIds.has(link.outcome)||!STRENGTHS.includes(link.strength))fail('link '+link.factor+'->'+link.outcome);
  const key=link.factor+'>'+link.outcome;if(pairs.has(key))fail('duplicate link '+key);pairs.add(key);
  return {factor:link.factor,outcome:link.outcome,strength:link.strength,...(link.definitional?{definitional:true}:{})};
});
const factors=data.factors.map(f=>({id:f.id,label:f.label,group:f.group||'',...(f.ace?{ace:true}:{})}));
const outcomes=data.outcomes.map(o=>({id:o.id,label:o.label,kind:o.kind,...(o.code?{code:o.code}:{}),...(typeof o.url==='string'&&/^\/(?!\/)/.test(o.url)?{url:o.url}:{}),...(o.note?{note:o.note}:{})}));
// Protective factors ("Ce qui m'a aidé") are answers too: Ambre needs their labels.
if(!Array.isArray(data.protections))fail('missing protections');
unique(data.protections,'protection');
const protections=data.protections.map(p=>({id:p.id,label:p.label}));
const module={schema_version:data.schema_version||1,weights,factors,outcomes,links,protections};
const output='// Generated by scripts/build_cartographie_module.mjs from data/cartographie.json. Do not edit.\n'+
  'export const CARTOGRAPHIE = '+JSON.stringify(module)+';\n';
const path=new URL('../journal/src/cartographie.generated.mjs',import.meta.url);
if(process.argv.includes('--check')){let current='';try{current=readFileSync(path,'utf8');}catch{}if(current!==output)throw new Error('Cartographie module is stale; run node scripts/build_cartographie_module.mjs');}
else writeFileSync(path,output);
