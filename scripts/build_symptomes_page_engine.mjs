import {readFileSync, writeFileSync} from 'node:fs';
// « Mes symptômes » (lot B) : the page computes the safety screen and the preview with the very
// engine the Worker uses (journal/src/symptomes-engine.mjs, no import, no DOM). This script copies
// its source, without the `export` keywords, into a string the Worker serves at
// /mes-symptomes/moteur.js. `--check` fails when the copy is stale.
const sourcePath=new URL('../journal/src/symptomes-engine.mjs',import.meta.url);
const source=readFileSync(sourcePath,'utf8');
if(/^\s*import\s/m.test(source))throw new Error('symptomes-engine.mjs must not import anything: the page runs it as a plain script');
const names=[...source.matchAll(/^export\s+(?:async\s+)?(?:function|const|let)\s+([A-Za-z_$][\w$]*)/gm)].map(match=>match[1]);
if(!names.length)throw new Error('No export found in symptomes-engine.mjs');
const body=source.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let)\s)/gm,'');
if(/^export\b/m.test(body))throw new Error('Unsupported export form in symptomes-engine.mjs');
const output='// Generated by scripts/build_symptomes_page_engine.mjs from journal/src/symptomes-engine.mjs. Do not edit.\n'+
 'export const SYMPTOMES_ENGINE_SOURCE = '+JSON.stringify(body)+';\n'+
 'export const SYMPTOMES_ENGINE_EXPORTS = '+JSON.stringify(names)+';\n';
const path=new URL('../journal/src/symptomes-engine-source.generated.mjs',import.meta.url);
if(process.argv.includes('--check')){let current='';try{current=readFileSync(path,'utf8')}catch{}if(current!==output)throw new Error('Symptoms page engine is stale; run node scripts/build_symptomes_page_engine.mjs');}
else writeFileSync(path,output);
