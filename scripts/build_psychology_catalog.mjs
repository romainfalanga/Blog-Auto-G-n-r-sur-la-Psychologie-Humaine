import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const source=new URL('../data/psychology_catalog.json',import.meta.url);
const target=new URL('../journal/src/psychology-catalog.generated.mjs',import.meta.url);
const idPattern=/^[a-z][a-z0-9_]*$/;
const kinds=new Set(['process','resource','context']);
const fail=message=>{throw new Error(`Invalid psychology catalog: ${message}`);};
const nonempty=value=>typeof value==='string'&&value.trim()===value&&value.length>0;
const text=(value,label)=>{if(!nonempty(value))fail(`${label} must be nonempty trimmed text`);};
function uniqueRecords(records,label){
 if(!Array.isArray(records)||!records.length)fail(`${label} must be a nonempty array`);
 const result=new Map();
 for(const record of records){
  if(!record||typeof record!=='object'||typeof record.id!=='string'||!idPattern.test(record.id))fail(`${label} has an invalid id`);
  if(result.has(record.id))fail(`${label} has duplicate id ${record.id}`);
  result.set(record.id,record);
 }
 return result;
}
function stringArray(value,label,min=1){
 if(!Array.isArray(value)||value.length<min||value.some(item=>!nonempty(item)))fail(`${label} needs at least ${min} nonempty strings`);
 if(new Set(value).size!==value.length)fail(`${label} has duplicate values`);
}

export function validatePsychologyCatalog(data){
 if(!data||data.version!==2)fail('version must be 2');
 text(data.scope,'scope');
 if(data.provenance?.mapping!=='editorial_family')fail('provenance must declare editorial_family');
 for(const key of ['note','inference_limits','health_context','common_labels'])text(data.provenance[key],`provenance.${key}`);
 const domains=uniqueRecords(data.domains,'domains');
 const subdomains=uniqueRecords(data.subdomains,'subdomains');
 const sources=uniqueRecords(data.sources,'sources');
 const patterns=uniqueRecords(data.patterns,'patterns');
 for(const domain of domains.values())text(domain.label,`domain ${domain.id}.label`);
 for(const subdomain of subdomains.values()){
  text(subdomain.label,`subdomain ${subdomain.id}.label`);
  if(!domains.has(subdomain.domain))fail(`subdomain ${subdomain.id} has unknown domain ${subdomain.domain}`);
 }
 for(const ref of sources.values()){
  for(const key of ['publisher','title','scope','consulted_at'])text(ref[key],`source ${ref.id}.${key}`);
  let url;try{url=new URL(ref.url);}catch{fail(`source ${ref.id} has invalid url`);}
  if(url.protocol!=='https:')fail(`source ${ref.id} must use https`);
  const date=Date.parse(ref.consulted_at);
  if(!/^\d{4}-\d{2}-\d{2}$/.test(ref.consulted_at)||Number.isNaN(date)||new Date(date).toISOString().slice(0,10)!==ref.consulted_at)fail(`source ${ref.id} has invalid consultation date`);
 }
 stringArray(data.provenance.source_refs,'provenance.source_refs');
 if(data.provenance.source_refs.some(id=>!sources.has(id)))fail('provenance has unknown source references');
 const labels=new Set(),descriptions=new Set(),usedDomains=new Set(),usedSubdomains=new Set();
 for(const pattern of patterns.values()){
  const label=`pattern ${pattern.id}`;
  if(!domains.has(pattern.domain))fail(`${label} has unknown domain ${pattern.domain}`);
  const subdomain=subdomains.get(pattern.subdomain);
  if(!subdomain||subdomain.domain!==pattern.domain)fail(`${label} has invalid subdomain ${pattern.subdomain} for domain ${pattern.domain}`);
  if(!kinds.has(pattern.kind))fail(`${label} has invalid kind ${pattern.kind}`);
  for(const key of ['label','description'])text(pattern[key],`${label}.${key}`);
  for(const [key,min] of [['signals',2],['alternatives',2],['questions',2],['keywords',3],['related',1],['source_refs',1]])stringArray(pattern[key],`${label}.${key}`,min);
  const normalized=pattern.label.normalize('NFKC').toLocaleLowerCase('fr');
  if(labels.has(normalized))fail(`${label} repeats a label`);
  if(descriptions.has(pattern.description))fail(`${label} repeats a description`);
  labels.add(normalized);descriptions.add(pattern.description);
  if(pattern.related.some(id=>!patterns.has(id)||id===pattern.id))fail(`${label} has invalid related references`);
  if(pattern.source_refs.some(id=>!sources.has(id)))fail(`${label} has unknown source references`);
  usedDomains.add(pattern.domain);usedSubdomains.add(pattern.subdomain);
 }
 for(const id of domains.keys())if(!usedDomains.has(id))fail(`domain ${id} has no patterns`);
 for(const id of subdomains.keys())if(!usedSubdomains.has(id))fail(`subdomain ${id} has no patterns`);
 return data;
}

export function generatePsychologyCatalog(data){
 validatePsychologyCatalog(data);
 return '// Generated by scripts/build_psychology_catalog.mjs; edit data/psychology_catalog.json.\nexport const PSYCHOLOGY_CATALOG = '+JSON.stringify(data,null,2)+';\n';
}

if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const output=generatePsychologyCatalog(JSON.parse(fs.readFileSync(source,'utf8')));
 if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Psychology catalog is out of date; run node scripts/build_psychology_catalog.mjs');
 }else fs.writeFileSync(target,output);
}
